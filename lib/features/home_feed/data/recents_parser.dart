import 'dart:convert';
import 'dart:developer' as dev;
import 'dart:typed_data';

import 'package:musify_mu/core/protocol/generated/spotify/playlist/recents_list.pb.dart'
    as recents;

enum RecentType { played, saved, shared, autoGenerated }

enum ContentCategory { unspecified, music, podcasts, audiobooks }

class RecentsItem {
  final String uri;
  final int songsCount;
  final RecentType recentType;
  final ContentCategory contentCategory;
  final bool isGroupHeader;
  final String groupName;
  final int timestamp;
  final List<String> entityUris;

  const RecentsItem({
    required this.uri,
    this.songsCount = 0,
    this.recentType = RecentType.played,
    this.contentCategory = ContentCategory.unspecified,
    this.isGroupHeader = false,
    this.groupName = '',
    this.timestamp = 0,
    this.entityUris = const [],
  });
}

/// Parses the protobuf response from /playlist/v2/list/recents/main
/// into structured RecentsItem objects with full metadata.
List<RecentsItem> parseRecentsItems(Uint8List data) {
  final items = <RecentsItem>[];

  try {
    final response = recents.RecentsListResponse.fromBuffer(data);

    for (final listItem in response.list.items) {
      final uri = listItem.uri;
      if (uri.isEmpty) continue;

      int songsCount = 0;
      bool isGroupHeader = false;
      String groupName = '';
      RecentType recentType = RecentType.played;
      ContentCategory contentCategory = ContentCategory.unspecified;
      int timestamp = 0;
      List<String> entityUris = const [];

      if (listItem.hasAttributes() && listItem.attributes.hasTimestamp()) {
        timestamp = listItem.attributes.timestamp.toInt();
      }

      for (final attr in listItem.attributes.formatAttributes) {
        switch (attr.key) {
          case 'group_id_0':
            isGroupHeader = true;
          case 'recent_type_saved':
            recentType = RecentType.saved;
          case 'recent_type_shared':
            recentType = RecentType.shared;
          case 'recent_type_auto_generated':
            recentType = RecentType.autoGenerated;
          case 'content_type_music':
            contentCategory = ContentCategory.music;
          case 'content_type_podcasts':
            contentCategory = ContentCategory.podcasts;
          case 'content_type_audiobooks':
            contentCategory = ContentCategory.audiobooks;
          case 'group_metadata':
            try {
              final decoded = base64.decode(attr.value);
              final meta = recents.GroupMetadata.fromBuffer(decoded);
              songsCount = meta.itemsCount;
              groupName = meta.groupName;
              entityUris = meta.entityUris.toList();
            } catch (e) {
              dev.log('Recents parse group metadata failed: $e');
            }
        }
      }

      items.add(RecentsItem(
        uri: uri,
        songsCount: songsCount,
        recentType: recentType,
        contentCategory: contentCategory,
        isGroupHeader: isGroupHeader,
        groupName: groupName,
        timestamp: timestamp,
        entityUris: entityUris,
      ));
    }
  } catch (e) {
    dev.log('RecentsParser: parse error: $e');
  }

  dev.log('Recents: ${items.length} items parsed');
  return items;
}
